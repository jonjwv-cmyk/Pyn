// ============================================================
// flow-warehouse.ts — ЕДИНАЯ нормализация кода склада для всего Потока.
// ============================================================
// Зачем: код склада приходит по-разному — «4801»/«04801», «0122»/«122», буквенные «824Т».
// Раньше каждый грид нормализовал по-своему (Plan — pad-to-4, Песочница — сырой + фолбэк,
// molIsGone — вообще без нормализации) → «где-то МОЛ пустой, где-то подсвечен». ТЗ §3:
// один helper во ВСЕХ местах (ключи карт, molsForWh, molIsGone, авто-МОЛ, тема строки).

/**
 * Канонический ключ кода склада для СРАВНЕНИЯ/поиска: trim + UPPER + снять ведущие нули.
 * Zero-insensitive: «4801»==«04801»→«4801»; «0122»==«122»→«122»; «824Т»→«824Т»; «0»→«0».
 * ВСЕ карты по складу и ВСЕ lookup'ы должны строиться/читаться через него.
 */
export function whKey(raw: string | null | undefined): string {
  return String(raw ?? '').trim().toUpperCase().replace(/^0+(\d)/, '$1');
}

/** map.get по складу зеро-нечувствительно (карта обязана быть собрана с ключами whKey). */
export function whMapGet<T>(map: ReadonlyMap<string, T>, raw: string | null | undefined): T | undefined {
  return map.get(whKey(raw));
}

/**
 * Отображение кода склада: числовой 1-3 знака → 4 знака с нулями («122» → «0122»);
 * буквенные/уже 4+ — как есть (trim/upper). ТОЛЬКО для показа, НЕ для сравнения.
 */
export function whDisplay(raw: string | null | undefined): string {
  const s = String(raw ?? '').trim().toUpperCase();
  return /^\d{1,3}$/.test(s) ? s.padStart(4, '0') : s;
}
