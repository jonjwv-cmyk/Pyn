/**
 * Сброс `days` в пусто (= нет фильтра, склад едет на всех natural-днях).
 * Codes остаются — стабильный список. Используется при смене месяца:
 * каждый месяц юзер заново решает какие дни ИМЕННО показывать.
 */
export function resetOverrideDaysForMonth(
  overrides: ScheduleOverrideRule[],
): ScheduleOverrideRule[] {
  return overrides.map((rule) => ({ ...rule, days: [] }));
}

/**
 * Inherit предыдущего snapshot'а как стартовая точка для нового (year, month).
 *
 * Holidays и approverDate — месяц-специфичные → СБРАСЫВАЮТСЯ.
 *   Иначе в июне торчат майские «1, 2, 3, 4, 11, 29, 30» что бессмысленно.
 * Overrides — список кодов стабилен между месяцами, но дни сбрасываются.
 *   Empty days = «нет фильтра» (склад идёт на всех natural-днях).
 * commit — никогда не наследуется (новый месяц всегда non-committed).
 *
 * shops / removedWarehouses / shippingWarehouses обнуляются — derive'ятся
 * клиентом из warehouses store для не-зафиксированных месяцев. После commit'а
 * этого месяца — будут заморожены отдельно.
 */
export function inheritForNewMonth(
  prior: ScheduleState,
  year: number,
  month: number,
): ScheduleState {
  return {
    meta: {
      ...prior.meta,
      year,
      month,
      holidays: [],
      approverDate: undefined,
      commit: undefined,
      overrides: resetOverrideDaysForMonth(prior.meta.overrides),
    },
    shops: [],
    removedWarehouses: [],
    shippingWarehouses: [],
  };
}

