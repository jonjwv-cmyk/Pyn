import { parseWarehouseCell } from './compute';
import type { ScheduleOverrideRule, ScheduleShop, ScheduleState, Weekday } from './types';

/** Парсер сырых данных из Excel в ScheduleShop. */
function shop(idx: number, name: string, rows: ReadonlyArray<[Weekday, string]>): ScheduleShop {
  return {
    id: `shop_${idx}`,
    idx,
    name,
    rows: rows.map(([weekday, rawWarehouses], rowIdx) => ({
      id: `shop_${idx}_row_${rowIdx + 1}`,
      weekday,
      warehouses: parseWarehouseCell(rawWarehouses),
    })),
  };
}

