/**
 * Производственный календарь РФ (по годам) — единый источник для расчёта смены,
 * окна доставки, длительности сессии и раздела «График».
 *
 * Источник правды данных — серверная таблица D1 `prod_calendar` (обновляется без
 * релиза EXE). Этот тип + `data.ts` (seed) — клиентский bootstrap/fallback, если
 * сервер ещё не отдал свежий календарь (первый запуск / офлайн / до деплоя).
 *
 * Все даты внутри года — строки `MM-DD` (без года, без ведущих пробелов), e.g.
 * `01-09`, `12-31`. Год берётся из `year`. Ноль-паддинг обязателен.
 */
export interface ProdCalendarYear {
  /** Полный год, e.g. 2026. */
  year: number;
  /**
   * Нерабочие ПРАЗДНИЧНЫЕ дни (и перенесённые) — те красные дни календаря,
   * которые НЕ выходные. Выходные (Сб/Вс) считаются нерабочими автоматически и
   * сюда НЕ входят. MM-DD.
   */
  holidays: string[];
  /**
   * Предпраздничные дни — продолжительность работы сокращена на 1 час (в
   * календаре помечены `*`). Это РАБОЧИЕ дни, просто смена короче. MM-DD.
   */
  shortDays: string[];
  /**
   * Выходные (Сб/Вс), которые в этом году РАБОЧИЕ (перенос рабочего дня на
   * субботу). В 2026 таких нет. MM-DD.
   */
  workingWeekends: string[];
}

/** Пачка календарей по годам: `{ 2026: {...}, 2027: {...} }`. */
export type ProdCalendarByYear = Record<number, ProdCalendarYear>;
